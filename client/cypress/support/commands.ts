declare namespace Cypress {
  interface Chainable {
    /**
     * Get one or more DOM elements by test id.
     *
     * @param id The test id
     * @param options The same options as cy.get
     */
    byTestId<E extends Node = HTMLElement>(
      id: string,
      options?: Partial<
        Cypress.Loggable &
          Cypress.Timeoutable &
          Cypress.Withinable &
          Cypress.Shadow
      >
    ): Cypress.Chainable<JQuery<E>>;

    findByTestId<E extends Node = HTMLElement>(
      id: string,
      options?: Partial<
        Cypress.Loggable &
          Cypress.Timeoutable &
          Cypress.Withinable &
          Cypress.Shadow
      >
    ): Cypress.Chainable<JQuery<E>>;

    expectUrl<E extends Node = HTMLElement>(
      pattern: string
    ): Cypress.Chainable<Location>;
  }
}

Cypress.Commands.add(
  "byTestId",
  <E extends Node = HTMLElement>(
    id: string,
    options?: Partial<
      Cypress.Loggable &
        Cypress.Timeoutable &
        Cypress.Withinable &
        Cypress.Shadow
    >
  ): Cypress.Chainable<JQuery<E>> => cy.get(`[data-testid="${id}"]`, options)
);

Cypress.Commands.add(
  "findByTestId",
  <E extends Node = HTMLElement>(
    id: string,
    options?: Partial<
      Cypress.Loggable &
        Cypress.Timeoutable &
        Cypress.Withinable &
        Cypress.Shadow
    >
  ): Cypress.Chainable<JQuery<E>> => cy.find(`[data-testid="${id}"]`, options)
);

Cypress.Commands.add(
  "expectUrl",
  (pattern: string): Cypress.Chainable<Location> =>
    cy.location().should((loc) => {
      expect(Cypress.minimatch(loc.pathname, pattern)).to.be.true;
    })
);
